/** Icon for a key point that only knows its body area (the shot's mistakes). */
export function focusIcon(focus: DrillFocus | null | undefined): DrillKeyPointIcon | null {
  if (focus === 'foot') return 'split'
  if (focus === 'elbow') return 'eye'
  if (focus === 'torso') return 'posture'
  if (focus === 'racket') return 'racket'
  return null
}

